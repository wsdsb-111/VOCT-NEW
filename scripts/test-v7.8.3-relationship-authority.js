"use strict";

const assert = require("assert");
const path = require("path");

const root = path.resolve(__dirname, "..");
const mainDir = path.join(root, "resources", "app", "out", "main");
const { createGameData } = require(path.join(mainDir, "game-data", "game-data"));
const GameData = createGameData({ fs: require("fs"), path, memorySystem: { verifyDirectedSummaryPersistence: () => ({ success: true }) }, memoryEngine: null, summariesDir: "", getHistoricalReferenceByYear: () => ({}) });
const gameData = Object.create(GameData.prototype);
gameData.playerID = 1;
const base = (id, fullName, gender, birthDate) => ({ id, fullName, gender, birthDate, opinionOfPlayer: null, opinions: [], relationsToPlayer: [], relationsToCharacters: [], parents: [], children: [], siblings: [] });
const player = base(1, "李思昭", "male", "975.1.1");
const lover = base(2, "李师师", "female", "985.1.1");
lover.relationsToPlayer = ["lover"];
lover.opinionOfPlayer = -25;
player.relationsToCharacters = [{ id: 2, relations: ["lover"] }];
player.opinions = [{ id: 2, opinon: -20 }];
const npcA = base(3, "赵甲", "male", "980.1.1");
const npcB = base(4, "钱乙", "female", "982.1.1");
npcA.relationsToCharacters = [{ id: 4, relations: ["friend"] }];
npcA.opinions = [{ id: 4, opinon: 37 }];
const olderBrother = base(5, "兄长", "male", "970.1.1");
const youngerBrother = base(6, "幼弟", "male", "980.1.1");
olderBrother.age = 30;
youngerBrother.age = 20;
olderBrother.siblings = [{ id: 6, birthDate: youngerBrother.birthDate }];
youngerBrother.siblings = [{ id: 5, birthDate: olderBrother.birthDate }];
const olderSister = base(7, "长姐", "female", "972.1.1");
const youngerSister = base(8, "幼妹", "female", "984.1.1");
olderSister.age = 28;
youngerSister.age = 16;
olderSister.siblings = [{ id: 8, birthDate: youngerSister.birthDate }];
youngerSister.siblings = [{ id: 7, birthDate: olderSister.birthDate }];
gameData.characters = new Map([player, lover, npcA, npcB, olderBrother, youngerBrother, olderSister, youngerSister].map((character) => [character.id, character]));

const playerNpc = gameData.getActiveParticipantRelationshipInfo(lover, [1]);
assert.match(playerNpc, /李师师 ↔ 李思昭/);
assert.match(playerNpc, /正式关系（李师师视角）：lover/);
assert.match(playerNpc, /当前好感（李师师对李思昭）：-25/);
const nonKin = gameData.getActiveParticipantRelationshipInfo(npcA, [4]);
assert.match(nonKin, /赵甲 ↔ 钱乙/);
assert.match(nonKin, /正式关系（赵甲视角）：friend/);
assert.match(nonKin, /当前好感（赵甲对钱乙）：37/);
assert.match(nonKin, /亲属关系（赵甲相对钱乙）：无/);
assert.match(gameData.getActiveParticipantRelationshipInfo(olderBrother, [6]), /亲属关系（兄长相对幼弟）：兄长是幼弟的哥哥/);
assert.match(gameData.getActiveParticipantRelationshipInfo(youngerBrother, [5]), /亲属关系（幼弟相对兄长）：幼弟是兄长的弟弟/);
assert.match(gameData.getActiveParticipantRelationshipInfo(olderSister, [8]), /亲属关系（长姐相对幼妹）：长姐是幼妹的姐姐/);
assert.match(gameData.getActiveParticipantRelationshipInfo(youngerSister, [7]), /亲属关系（幼妹相对长姐）：幼妹是长姐的妹妹/);
assert.match(playerNpc, /全部当前在场人物关系权威层/);
assert.match(playerNpc, /正式关系与好感数值必须分开理解/);
assert.match(playerNpc, /当前 CK3 数据表示现在，摘要\/记忆只表示过去/);
assert.match(playerNpc, /发生冲突时以当前 CK3 正式关系和好感为准/, "historical summaries must not override current CK3 relationships");
console.log("VOTC v7.8.3 relationship authority: PASS (all active participants, formal relation, opinion, current-vs-past)");
